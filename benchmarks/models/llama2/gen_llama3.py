def generate(n: int) -> tuple[str, str, str]:
    name = f"llama3_8B_w8a8_n{n}"
    layer_bytes = L * (QKV + H + 3 * F) * H
    values = dict(
        NAME=name,
        N=n,
        H=H,
        F=F,
        L=L,
        A=A,
        KVH=KVH,
        V=V,
        VPAD=VPAD,
        HEAD=HEAD,
        KV=KV,
        QKV=QKV,
        GROUP=GROUP,
        GROUP_COLS=GROUP * HEAD,
        PAIRS=PAIRS,
        KPAIRS=KPAIRS,
        VOFF=H + KV,
        emb=mib(V * H),
        layers=gib(layer_bytes),
        cls=mib(VPAD * H),
        rope=mib(2 * n * PAIRS * 4),
        caches=mib(2 * L * n * KV),
        wqkv=mib(QKV * H),
        wf=mib(F * H),
        wo=mib(H * H),
        ROPE_Q=ROPE.substitute(fn="irope_q", W=H, P=PAIRS),
        ROPE_K=ROPE.substitute(fn="irope_k", W=KV, P=KPAIRS),
        REQUANTS="\n".join(
            REQUANT.substitute(fn=fn, W=w)
            for fn, w in (("requant_v", H), ("requant_qkv", QKV), ("requant_f", F))
        ),
    )
    return name, MLIR.substitute(values), CPP.substitute(values)


def main() -> None:
    for n in CONTEXTS:
        name, mlir, cpp = generate(n)
        (HERE / f"{name}.mlir").write_text(mlir)
        (HERE / f"{name}.cpp").write_text(cpp)
        print(f"wrote {name}.mlir, {name}.cpp")


if __name__ == "__main__":
    main()
