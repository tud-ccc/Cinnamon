"""tab:capability (a1.csv): geomean slowdown when a capability is disabled.

One row per benchmark, one column per restricted space (no MRAM tiling /
no scatter specialisation / neither), each the geomean over fns of
best_restricted / best_default. An infeasible cell (the restricted space
measured nothing, n_measured = 0) prints as $\\emptyset$ -- it is a result
("the level buys feasibility before it buys speed"), never dropped.
"""

from __future__ import annotations

import sys

from _reporting import geomean, load_or_skip, parse_dirs, tex, write_tex

SPACES = ["no_mram", "no_scatter", "neither"]


def main() -> None:
    results_dir, out_dir = parse_dirs("tables")
    df = load_or_skip(results_dir, "a1.csv")
    if df is None:
        return

    lines = [
        "% tab:capability, generated by table_capability.py -- do not edit",
        "\\begin{tabular}{l" + "r" * len(SPACES) + "}",
        "\\toprule",
        "benchmark & " + " & ".join(s.replace("_", "\\_") for s in SPACES) + " \\\\",
        "\\midrule",
    ]
    for bench, sub in df.groupby("benchmark"):
        default = sub[sub["space"] == "default"].set_index("fn_name")[
            "best_measured_ms"
        ]
        cells = []
        for space in SPACES:
            rows = sub[sub["space"] == space]
            if rows.empty:
                cells.append("--")  # not run yet: a hole, unlike infeasible
                continue
            if (rows["n_measured"] == 0).all():
                cells.append("$\\emptyset$")
                continue
            ratios = [
                float(r["best_measured_ms"]) / float(default[r["fn_name"]])
                for _, r in rows.iterrows()
                if r["n_measured"] > 0 and r["fn_name"] in default.index
            ]
            cells.append(f"{geomean(ratios):.2f}$\\times$" if ratios else "--")
        lines.append(f"{tex(bench)} & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    write_tex(out_dir, "capability.tex", lines)


if __name__ == "__main__":
    sys.exit(main())
