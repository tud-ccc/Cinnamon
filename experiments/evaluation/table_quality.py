"""tab:quality-configs (rq1.csv): the best measured configuration per
benchmark and system, total + component breakdown -- the companion table of
fig:quality, and where the CINM 1.0 rows live (published point, best of
sweep, rule-decision point) since a bar for them would dominate the figure's
scale without adding information.
"""

from __future__ import annotations

import sys

from _reporting import load_or_skip, parse_dirs, tex, write_tex

COMPONENTS = ["scatter_ms", "kernel_ms", "gather_ms", "load_ms"]


def _fmt(v) -> str:
    try:
        return f"{float(v):.2f}"
    except (TypeError, ValueError):
        return "--"


def main() -> None:
    results_dir, out_dir = parse_dirs("tables")
    df = load_or_skip(results_dir, "rq1.csv")
    if df is None:
        return

    best = df.loc[
        df.dropna(subset=["total_ms"])
        .groupby(["benchmark", "system"])["total_ms"]
        .idxmin()
    ]
    lines = [
        "% tab:quality-configs, generated by table_quality.py -- do not edit",
        "\\begin{tabular}{llllrrrrr}",
        "\\toprule",
        "benchmark & system & fn & config & total & scatter & kernel & gather & load \\\\",
        "\\midrule",
    ]
    for _, row in best.sort_values(["benchmark", "system"]).iterrows():
        lines.append(
            " & ".join(
                [
                    tex(row["benchmark"]),
                    tex(row["system"]),
                    tex(row.get("fn_name", "--")),
                    tex(row.get("config_label", "--")),
                    _fmt(row["total_ms"]),
                    *(_fmt(row.get(c)) for c in COMPONENTS),
                ]
            )
            + " \\\\"
        )
    lines += ["\\bottomrule", "\\end{tabular}"]
    write_tex(out_dir, "quality_configs.tex", lines)


if __name__ == "__main__":
    sys.exit(main())
