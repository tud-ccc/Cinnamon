"""tab:walltime (rq2.csv): what a search costs, per benchmark.

Ours: the space-construction time (offline setup, available as soon as B0
ran -- so this table has rows before any search) plus median search wall
clock and candidate count over seeds and fns. ATiM's column is the wall
clock of running their autotuner on this machine (system=atim_reproduced,
folded into rq2.csv from the offline interchange); until those runs exist
it prints --. The schedules published with their artifact have no column
here: they were tuned on the authors' hardware, so their cost is not
measurable by us and not comparable to ours.
"""

from __future__ import annotations

import sys

from _reporting import load_or_skip, parse_dirs, tex, write_tex


def _fmt(v) -> str:
    try:
        f = float(v)
    except (TypeError, ValueError):
        return "--"
    return "--" if f != f else f"{f:.1f}"  # NaN check without numpy


def main() -> None:
    results_dir, out_dir = parse_dirs("tables")
    df = load_or_skip(results_dir, "rq2.csv")
    if df is None:
        return

    lines = [
        "% tab:walltime, generated by table_walltime.py -- do not edit",
        "\\begin{tabular}{lrrrr}",
        "\\toprule",
        "benchmark & space build (s) & search (s, median/seed) & candidates"
        " & ATiM autotune (s) \\\\",
        "\\midrule",
    ]
    for bench, sub in df.groupby("benchmark"):
        ours = sub[sub["system"] == "ours"]
        atim = sub[sub["system"] == "atim_reproduced"]["search_wallclock_s"].dropna()
        build = ours["space_build_s"].dropna()
        search = ours["search_wallclock_s"].dropna()
        cands = ours["n_candidates"].dropna()
        lines.append(
            " & ".join(
                [
                    tex(bench),
                    _fmt(build.sum() if len(build) else None),
                    _fmt(search.median() if len(search) else None),
                    _fmt(cands.median() if len(cands) else None),
                    _fmt(atim.median() if len(atim) else None),
                ]
            )
            + " \\\\"
        )
    lines += ["\\bottomrule", "\\end{tabular}"]
    write_tex(out_dir, "walltime.tex", lines)


if __name__ == "__main__":
    sys.exit(main())
