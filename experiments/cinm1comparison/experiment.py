#!/usr/bin/env python3
"""
CINM 2.0 vs CINM 1.0 codegen comparison at matched (dpus, tasklets) working
groups.

Since CINM 1.0 has no search algorithm, we compare the performance of the
code generated by CINM 2.0 and CINM 1.0 for the *same* hardware
configuration:

  1. screen(): sweep CINM 2.0's configuration space with an additional
     constraint disabling MRAM tiling (CINM 1.0's own best configs are known
     to lie in this constrained subspace), score every valid config with the
     cost model, keep the best fraction (at least min_configs), and take the
     union of (dpus, tasklets) pairs used by any of them. This only narrows
     down which working groups are worth spending real hardware measurements
     on -- CINM 1.0's own tile shape for a given working group is inferred by
     the compiler itself (--cinm-infer-tile-sizes, no search), not something
     screened for (see cinm_experiments/cinm1.py).

  2. build_cinm1_configs(): for each selected working group, a Config whose
     lower() runs --cinm-infer-tile-sizes + the rest of the CINM 1.0 flow for
     that fixed (dpus, tasklets) -- no compiling yet.

  3. build_cinm2_configs(): for each selected working group, run CINM 2.0's
     Bayesian search n_seeds times with (dpus, tasklets) pinned (MRAM tiling
     enabled -- CINM 2.0's normal codegen), then a Config per seed's best
     result whose lower() replays that exact config with eval-solution.

  4. Both systems' configs are compiled together in one parallel batch, then
     (unless --compile-only) benchmarked together in one sequential pass --
     sequential because concurrent hardware runs contend for host/DPU
     resources and skew wall-clock timing.

  5. compare(): geomean speedup of CINM 2.0 (seed-median) over CINM 1.0 per
     working group, aggregated per benchmark and overall.

Run: python3 experiment.py [--prims prim_gemv prim_red] [--data-dir data] [--compile-only]
"""
from __future__ import annotations

import argparse
import os
import pathlib
import sys
from tqdm import tqdm

import pandas as pd

HERE = pathlib.Path(__file__).resolve().parent
EXPERIMENTS_DIR = HERE.parent
sys.path.insert(0, str(EXPERIMENTS_DIR))

from cinm_experiments import cinm1, cinmopt, compile_run, measurements, pools  # noqa: E402
from cinm_experiments.paths import DEFAULT_CINM_OPT  # noqa: E402
from cinm_experiments.split_source import split_source  # noqa: E402

from plot import plot_speedup, print_summary  # noqa: E402

DEFAULT_OPTS = dict(
    top_frac=0.10,
    min_configs=200,
    n_seeds=32,
    iters=10,
    screen_sim="cycle-accurate",
    workers=os.cpu_count(),
)


def screen(prim_mlir: pathlib.Path, data_dir: pathlib.Path, *, top_frac: float,
           min_configs: int, screen_sim: str, workers: int,
           cinm_opt: pathlib.Path):
    """Stage 1 -- see module docstring. Splits prim_mlir into one module per
    function first, then screens each function separately (its config space
    -- problem size, valid tile shapes -- is its own, so screening must be
    per function, not pooled across the whole file)."""
    split_dir = data_dir / "_split"
    modules = split_source(prim_mlir, split_dir)

    screen_dir = data_dir / "screen"
    selected: dict[str, tuple[pd.DataFrame, pathlib.Path]] = {}
    for fn_name, fn_module in tqdm(modules.items(), desc="Screening", total=len(modules)):
        cinmopt.exhaustive_search(
            fn_module, screen_dir, workers=workers,
            infer_opts={"use-mram-tiling": False, "simulator": screen_sim},
            cinm_opt=cinm_opt,
        )
        pool_csv = screen_dir / f"infer_{fn_name}" / "pool.csv"
        if not pool_csv.exists():
            tqdm.write(f"  WARNING: no pool.csv for {fn_name}", file=sys.stderr)
            continue
        top, n_valid, n_kept = pools.select_best(
            pool_csv, top_frac=top_frac, min_configs=min_configs
        )
        if top.empty:
            tqdm.write(f"  WARNING: no valid configs for {fn_name}", file=sys.stderr)
            continue
        # (dpus, tasklets) pairs used by any of the kept configs -- this is
        # the specific screening question this experiment asks; pools.py
        # only knows how to rank/keep a top fraction of a pool.
        pairs = (
            top[["dpus", "tasklets"]]
            .drop_duplicates()
            .sort_values(["dpus", "tasklets"])
            .reset_index(drop=True)
        )
        tqdm.write(f"  {fn_name:20s}  kept {n_kept} of {n_valid} valid rows"
              f" -> {len(pairs)} (dpus,tasklets) pairs")
        selected[fn_name] = (pairs, fn_module)
    return selected, screen_dir


def build_cinm1_configs(prim: str, selected: dict, *, cinm_opt: pathlib.Path) -> list[compile_run.Config]:
    """Stage 2 -- see module docstring. No compiling yet."""
    return [
        compile_run.Config(
            system="cinm1", fn_name=fn_name, label=f"D{dpus}_T{tasklets}",
            params={"dpus": int(dpus), "tasklets": int(tasklets)},
            fn_module=fn_module, prim=prim,
            lower=cinm1.lowerer(int(dpus), int(tasklets), cinm_opt=cinm_opt),
        )
        for fn_name, (pairs, fn_module) in selected.items()
        for dpus, tasklets in pairs.itertuples(index=False)
    ]


# Seed k in a multiseed run uses k*31+offset for k in 1..n_seeds; offsets must
# be spaced by more than n_seeds*31 apart so different pairs' seed_* dirs
# never collide within the same {fn_name}/ results directory.
_OFFSET_STRIDE = 4096
_BASE_OFFSET = 67


def build_cinm2_configs(prim: str, selected: dict, data_dir: pathlib.Path, *, n_seeds: int,
                         cinm_opt: pathlib.Path, workers: int) -> list[compile_run.Config]:
    """Stage 3 -- see module docstring. Runs the BO search (that's search,
    not compiling); returns Configs, not compiled yet."""
    if n_seeds * 31 >= _OFFSET_STRIDE:
        sys.exit(f"n_seeds {n_seeds} too large for offset stride {_OFFSET_STRIDE}")

    results_dir = data_dir / "cinm2_results"
    for fn_name, (pairs, fn_module) in selected.items():
        for pair_idx, (dpus, tasklets) in enumerate(pairs.itertuples(index=False)):
            offset = _BASE_OFFSET + pair_idx * _OFFSET_STRIDE
            print(f"  {fn_name} dpus={dpus} tasklets={tasklets}: BO search "
                  f"({n_seeds} seeds, offset={offset})")
            cinmopt.bo_multiseed(
                fn_module, results_dir, n_seeds=n_seeds, offset=offset, workers=workers,
                infer_opts={"fixed-dpus": int(dpus), "fixed-tasklets": int(tasklets)},
                cinm_opt=cinm_opt,
            )

    return [
        compile_run.Config(
            system="cinm2", fn_name=fn_name, label=seed, params=params,
            fn_module=selected[fn_name][1], prim=prim,
            lower=cinmopt.eval_solution_lowerer(params, cinm_opt=cinm_opt),
        )
        for fn_name, seed, params in pools.best_per_seed(results_dir)
    ]


def compare(cinm1_results: list[compile_run.RunResult],
            cinm2_results: list[compile_run.RunResult]) -> pd.DataFrame:
    """Stage 4 -- merge CINM 1.0 (one point per working group) with CINM 2.0
    (n_seeds points per working group -> seed-median) into a speedup table
    keyed by (fn_name, dpus, tasklets)."""
    cinm1 = measurements.results_to_frame(cinm1_results).drop(columns=["label"])
    cinm1 = cinm1.rename(columns={"net_time_ms": "cinm1_ms"})

    cinm2_raw = measurements.results_to_frame(cinm2_results)
    cinm2_summary = (
        cinm2_raw.groupby(["fn_name", "dpus", "tasklets"])["net_time_ms"]
        .agg(cinm2_ms="median",
             cinm2_p25=lambda s: s.quantile(0.25),
             cinm2_p75=lambda s: s.quantile(0.75),
             cinm2_n="count")
        .reset_index()
    )

    merged = cinm1.merge(cinm2_summary, on=["fn_name", "dpus", "tasklets"], how="inner")
    missing = set(zip(cinm1.fn_name, cinm1.dpus, cinm1.tasklets)) - set(
        zip(merged.fn_name, merged.dpus, merged.tasklets)
    )
    if missing:
        print(f"  WARNING: {len(missing)} (fn_name,dpus,tasklets) pairs have CINM1 "
              f"but no CINM2 data: {sorted(missing)[:5]}...", file=sys.stderr)
    merged["speedup"] = merged["cinm1_ms"] / merged["cinm2_ms"]
    return merged


def run_experiment(prim: str, *, data_root: pathlib.Path, cinm_opt: pathlib.Path,
                    opts: dict, compile_only: bool, run_only: bool) -> pd.DataFrame | None:
    prim_mlir = EXPERIMENTS_DIR / f"{prim}.mlir"
    data_dir = data_root / prim
    data_dir.mkdir(parents=True, exist_ok=True)
    op = prim.removeprefix("prim_")

    print(f"\n=== {prim}: screening ===")
    selected, screen_dir = screen(
        prim_mlir, data_dir, top_frac=opts["top_frac"], min_configs=opts["min_configs"],
        screen_sim=opts["screen_sim"], workers=opts["workers"], cinm_opt=cinm_opt,
    )
    pd.concat(
        [pairs.assign(fn_name=fn_name) for fn_name, (pairs, _fn_module) in selected.items()],
        ignore_index=True,
    ).to_csv(screen_dir / "selected_pairs.csv", index=False)

    print(f"\n=== {prim}: CINM 1.0 configs ===")
    cinm1_configs = build_cinm1_configs(op, selected, cinm_opt=cinm_opt)

    print(f"\n=== {prim}: CINM 2.0 search ===")
    cinm2_configs = build_cinm2_configs(
        op, selected, data_dir, n_seeds=opts["n_seeds"],
        cinm_opt=cinm_opt, workers=opts["workers"],
    )

    all_configs = cinm1_configs + cinm2_configs
    if run_only:
        print(f"\n=== {prim}: discovering {len(all_configs)} already-compiled configs ===")
        compiled = compile_run.discover_compiled(all_configs, compile_root=data_dir / "compiled")
    else:
        print(f"\n=== {prim}: compiling {len(all_configs)} configs "
              f"({len(cinm1_configs)} CINM1, {len(cinm2_configs)} CINM2) ===")
        compiled = compile_run.compile_configs(
            all_configs, compile_root=data_dir / "compiled", workers=opts["workers"],
        )

    if compile_only:
        return None

    print(f"\n=== {prim}: running {len(compiled)} configs ===")
    results = compile_run.run_configs(compiled, run_root=data_dir / "run", iters=opts["iters"])

    cinm1_results = [r for r in results if r.compiled.config.system == "cinm1"]
    cinm2_results = [r for r in results if r.compiled.config.system == "cinm2"]

    cmp_df = compare(cinm1_results, cinm2_results)
    cmp_df["prim"] = prim
    return cmp_df


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--prims", nargs="+", default=["prim_gemv", "prim_red"])
    ap.add_argument("--data-dir", default=str(HERE / "data"))
    ap.add_argument("--cinm-opt", default=str(DEFAULT_CINM_OPT))
    compile_group = ap.add_mutually_exclusive_group()
    compile_group.add_argument("--compile-only", action="store_true",
                                help="Compile every selected config but don't benchmark or plot")
    compile_group.add_argument("--run-only", action="store_true",
                                help="Skip compiling; benchmark configs already compiled by a "
                                     "previous --compile-only run")
    args = ap.parse_args()

    data_root = pathlib.Path(args.data_dir)
    opts = {**DEFAULT_OPTS}
    comparisons = [
        run_experiment(prim, data_root=data_root, cinm_opt=pathlib.Path(args.cinm_opt),
                       opts=opts, compile_only=args.compile_only, run_only=args.run_only)
        for prim in args.prims
    ]
    if args.compile_only:
        return

    comparison = pd.concat(comparisons, ignore_index=True)

    out_dir = data_root / "plots"
    out_dir.mkdir(parents=True, exist_ok=True)
    comparison.to_csv(out_dir / "comparison.csv", index=False)

    print_summary(comparison)
    plot_speedup(comparison, out_dir)


if __name__ == "__main__":
    main()
